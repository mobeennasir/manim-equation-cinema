_TRANSFORMATIONS = standard_transformations + (
    convert_xor,
    implicit_multiplication_application,
)

_ALLOWED = {
    "sin": sp.sin, "cos": sp.cos, "tan": sp.tan,
    "exp": sp.exp, "log": sp.log, "ln": sp.log,
    "sqrt": sp.sqrt, "abs": sp.Abs, "cosh": sp.cosh, "sinh": sp.sinh,
    "pi": sp.pi, "e": sp.E,
}


def parse_expression(text, variable):
    """Parse one maths string into a SymPy expression in `variable`."""
    if text is None or str(text).strip() == "":
        raise ValueError("Empty equation — type something, e.g.  sin(x)")
    cleaned = str(text).strip()
    if "=" in cleaned:
        cleaned = cleaned.split("=", 1)[1].strip()
    try:
        expr = parse_expr(
            cleaned,
            local_dict={**_ALLOWED, variable: sp.Symbol(variable)},
            transformations=_TRANSFORMATIONS,
            evaluate=True,
        )
    except Exception as exc:  # noqa: BLE001
        raise ValueError(f"Could not understand '{text}'. Check brackets and spelling. ({exc})") from exc
    if expr.free_symbols - {sp.Symbol(variable)}:
        raise ValueError(
            f"'{text}' uses a letter other than '{variable}'. "
            f"For this mode use only '{variable}'."
        )
    return expr


def make_function(text, variable):
    """Return (sympy_expr, numpy_callable) for one expression string."""
    expr = parse_expression(text, variable)
    func = sp.lambdify(sp.Symbol(variable), expr, modules=["numpy"])
    return expr, func


def latex_of(text, variable):
    try:
        return sp.latex(parse_expression(text, variable))
    except ValueError:
        return text


def lorenz_points(n=4000):
    """Lorenz attractor (sigma=10, rho=28, beta=8/3), x-y view, scaled /10."""
    sigma, rho, beta, dt = 10.0, 28.0, 8.0 / 3.0, 0.01
    x, y, z = 0.1, 0.0, 0.0
    xs, ys = np.empty(n), np.empty(n)
    for i in range(n):
        def f(x_, y_, z_):
            return sigma * (y_ - x_), x_ * (rho - z_) - y_, x_ * y_ - beta * z_
        k1 = f(x, y, z)
        k2 = f(x + dt / 2 * k1[0], y + dt / 2 * k1[1], z + dt / 2 * k1[2])
        k3 = f(x + dt / 2 * k2[0], y + dt / 2 * k2[1], z + dt / 2 * k2[2])
        k4 = f(x + dt * k3[0], y + dt * k3[1], z + dt * k3[2])
        x += dt / 6 * (k1[0] + 2 * k2[0] + 2 * k3[0] + k4[0])
        y += dt / 6 * (k1[1] + 2 * k2[1] + 2 * k3[1] + k4[1])
        z += dt / 6 * (k1[2] + 2 * k2[2] + 2 * k3[2] + k4[2])
        xs[i], ys[i] = x / 10.0, y / 10.0
    return xs, ys


