    path = path or os.environ.get("EQ_CONFIG") or os.path.join(
        os.path.dirname(os.path.abspath(__file__)), "equation.json"
    )
    if os.path.exists(path):
        with open(path, encoding="utf-8") as fh:
            return json.load(fh)
