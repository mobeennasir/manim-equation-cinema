"""
equations.py — parse ANY maths equation safely and turn it into points.

Modes
-----
1. "y"          : y = f(x)            e.g.  y = sin(x)
2. "parametric" : x(t) = ..., y(t) = ...   e.g. the butterfly curve
3. "polar"      : r(theta) = ...      e.g.  r = 2*sin(3*theta)
4. "lorenz"     : the Lorenz attractor (chaos / butterfly effect), x-y view.
                  No formula to type — it is generated by the Lorenz ODEs.
5. "chords"     : times-table art — N points on a circle, each joined to
                  its multiple (n -> k*n mod N). Draws the cardioid web.
6. "dots"       : dot spiral — n dots placed at a fixed angle step
                  (e.g. the golden angle 137.508 deg), radius growing
                  as sqrt(i). Draws the sunflower.
7. "morph-chords": the full times-table morph — dots start on a
                  straight number line, the line bends into a circle,
                  then the chords bloom into the cardioid.
8. "showcase"   : several equations back to back, hard cuts, 3-5 s
                  each — the fast roses-showcase format.

Extra per-preset keys (all optional):
  "color":       one colour for the whole preset (e.g. "#ffffff" for a
                 black-and-white pi). Otherwise the first curve's colour.
  "gradient":    [colour1, colour2] — the line changes colour along its
                 length as it draws (butterfly: pink -> blue).
  "wing_colors": [colour_left, colour_right] — Lorenz: one colour per
                 wing, coloured by the sign of x.
  "simultaneous": true — draw all curves at the same time (a race),
                 instead of one after another.
  "text" may also carry "title_fades": true — the title (and the
                 formula line) fade out halfway, once the picture
                 takes over (the pi reel).

How to add a new equation — copy the TEMPLATE below into PRESETS
---------------------------------------------------------------
Every preset defines FOUR things, all in this one file:
  1. The maths (mode + expr / x_expr / y_expr / chords / dots params).
  2. "story":    the hook + payoff in plain words — WHY this graph is
                 viral, written from HOW THE GRAPH DRAWS. Read the graph
                 first: what does it do? (It blooms? It races? It never
                 closes? Two lines chase each other?) That behaviour IS
                 the story. Never write a story the graph does not show.
  3. "camera_style" + "camera_note": how the camera moves for THIS
                 equation. Styles: "push-in" (slow zoom in while it
                 draws), "zoom-out" (start close, pull back as the
                 picture grows — for curves that fill the screen),
                 "pan" (follow the drawing left to right — for waves
                 and races), "wide" (no camera moves, fixed frame).
                 camera_note is the plain-English direction.
  4. "text":     on-screen words. "hook" = opening line shown first,
                 "payoff" = closing line shown at the end, "caption" =
                 one line under the drawing, "labels" = text that rides
                 the curves, each {"text", "color", "curve" (index),
                 "rides": "dot" (follows the white dot) | "start" |
                 "end"}. Omit any key you do not need.
  Plus "viral" (1-5), "why" (one line for the website list) and
  "audio" (a key from audio.py: butterfly, lorenz, rose, heart,
  spirograph, lissajous, spiral, waves, fourier, calm).

Multi-colour: a preset (or a custom config) can hold several curves in
"curves": [...]. Each curve has its own colour. The scene draws them one
after another, each in its own colour — so 2, 3 or 4 lines in one video.

You type normal maths:  sin, cos, tan, exp, log, sqrt, pi, e, abs, ^ for power.
Example:  sin(x)^2 + cos(x)^2   or   x^2 / 4

No Python code is ever run from your input — it is parsed with SymPy,
so typing an equation cannot run anything nasty on your computer.
"""

