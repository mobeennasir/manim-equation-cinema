def curves_from_config(cfg):
    """Normalise any config (single-curve legacy or multi-curve) to a list."""
    if cfg.get("curves"):
        return list(cfg["curves"])
    mode = cfg.get("mode", "y")
    color = cfg.get("color", "#22d3ee")
    if mode == "y":
        return [{"mode": "y", "expr": cfg["expr"], "x_min": cfg.get("x_min", -6),
                 "x_max": cfg.get("x_max", 6), "color": color, "label": cfg.get("title", "")}]
    if mode == "parametric":
        return [{"mode": "parametric", "x_expr": cfg["x_expr"], "y_expr": cfg["y_expr"],
                 "t_min": cfg.get("t_min", 0), "t_max": cfg.get("t_max", 6.28),
                 "color": color, "label": cfg.get("title", "")}]
    if mode == "polar":
        return [{"mode": "polar", "expr": cfg["expr"],
                 "t_min": cfg.get("t_min", 0), "t_max": cfg.get("t_max", 6.28),
                 "color": color, "label": cfg.get("title", "")}]
    if mode == "lorenz":
        return [{"mode": "lorenz", "color": color, "label": cfg.get("title", ""),
                 **({"wing_colors": cfg["wing_colors"]} if cfg.get("wing_colors") else {})}]
    if mode == "chords":
        return [{"mode": "chords", "points": cfg.get("points", 200),
                 "multiple": cfg.get("multiple", 3), "radius": cfg.get("radius", 2.5),
                 "color": color, "label": cfg.get("title", "")}]
    if mode == "morph-chords":
        # Validated like chords; the scene draws the morph itself.
        return [{"mode": "chords", "points": cfg.get("points", 200),
                 "multiple": cfg.get("multiple", 3), "radius": cfg.get("radius", 2.5),
                 "color": color, "label": cfg.get("title", "")}]
    if mode == "showcase":
        # Each item is already a curve dict (polar, with its own colour).
        return list(cfg.get("items", []))
    if mode == "dots":
        return [{"mode": "dots", "n": cfg.get("n", 600),
                 "angle": cfg.get("angle", 137.508), "spacing": cfg.get("spacing", 0.12),
                 "color": color, "label": cfg.get("title", "")}]
    raise ValueError(f"Unknown mode '{mode}'. Use y, parametric, polar, lorenz, chords, morph-chords, showcase or dots.")


